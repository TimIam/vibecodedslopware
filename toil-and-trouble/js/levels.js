// levels.js — every level as ASCII, written in vertical slices that are joined left to right.
//
// tiles:   # ground   = one-way ledge   ^ thorns/spikes   ~ bog water / magma   H cracked wall (a thrown cauldron breaks it)
//          r rail (one-way)   : backdrop (no collision)
// player:  S start   G exit cauldron   * checkpoint cauldron
// pickups: o tarot card   % fanned hand of cards (10)   1 2 3 4 the letters B R E W   @ cat token (1UP)   p spellbook page
// pots:    c cauldron to throw   i iron cauldron (rolls, bounces, ride it)   x volatile brew (explodes)   + coven cauldron (frees your partner)
// cannons: O blast cauldron (options in `cannons`, in play order)   ? bonus cauldron (options in `bonus`)
// brooms:  B broom rack (touch to ride; C hops off and leaves it standing)
// motion:  M moving ledge (run of Ms = one ledge, options in `movers`)   f crumbling ledge   m bounce toadstool/bell
// enemies: y friar   d deacon (shield)   h hedgehog   s slug   b bishop   t acolyte (throws candles)   k crow (patrols)   K crow (bobs)
//          w wasp (bobs)   W wasp (patrols)   u rider in a mine cart
// boss:    X the Witchfinder   D cauldron drop point
// Play order (for the option lists) is left to right, then top to bottom; order:'y' levels count bottom to top.

const seg = (s) => s.replace(/^\n/, '').replace(/\n\s*$/, '').split('\n');
function join(...blocks) {
  const segs = blocks.map(seg);
  const n = segs[0].length;
  segs.forEach((b, i) => { if (b.length !== n) throw new Error(`slice ${i} has ${b.length} rows, expected ${n}`); });
  const rows = [];
  for (let r = 0; r < n; r++) rows.push(segs.map((b) => b[r].padEnd(Math.max(...b.map((l) => l.length)), '.')).join(''));
  return rows;
}

