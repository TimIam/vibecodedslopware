// Builds caseodle/words.js, the list of guesses CaseOdle accepts. The answers (all food) live in
// caseodle/index.html; this list only decides what counts as a real word.
// Source: /usr/share/dict/web2 (Webster's Second, public domain, ships with macOS), plus the regular
// plurals and past tenses it leaves out, plus a few words it is too old to know.
//   node tools/caseodle-words.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const EXTRA = `going doing being lying dying tying eying fried tried dried cried spied plied
  emoji email memes vibes gamer yummy tasty spicy juicy zesty nutty minty fishy salty meaty chewy
  gooey smoky soggy tangy saucy crispy cheesy nuggs boba boxed boxes fixed mixed taxed waxed foxes`.split(/\s+/);

const dict = readFileSync('/usr/share/dict/web2', 'utf8').split('\n').filter(w => /^[a-z]+$/.test(w));
const out = new Set(EXTRA.filter(w => w.length === 5));
for (const w of dict) {
  if (w.length === 5) out.add(w);
  else if (w.length === 4) {
    out.add(w + 's');
    if (w.endsWith('e')) out.add(w + 'd');
  } else if (w.length === 3) {
    out.add(w + 'ed');
    if (/[sxzh]$/.test(w)) out.add(w + 'es');
  }
}

const words = [...out].sort();
writeFileSync(new URL('../caseodle/words.js', import.meta.url),
  `// Accepted CaseOdle guesses, five letters each, packed. Generated by tools/caseodle-words.mjs.\n` +
  `window.CASEODLE_GUESSES="${words.join('')}";\n`);
console.log(`${words.length} guesses`);
