// Rebuilds lib/storefront/catalog.json: which game owns which source id on which platform.
//
//   node tools/storefront-catalog.mjs
//
// Derived automatically (rewritten every run):
//   * site_asset    every downloadable file tracked in git (outside v/), keyed by its site path
//   * curseforge    project ids from tools/addon-watch/config.json (the ids the release bot uploads to)
// Kept as written (add these by hand, with "manual": true):
//   * itch / steam / epic / github / store_page entries, with the platform's own id and public url.
//     Only add an id you have read from that platform's dashboard; never guess one.
//
// The sync endpoint upserts this file into storefront.listings. /api/track only counts files and
// store links that are in it.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "lib/storefront/catalog.json");
const DOWNLOAD = /\.(zip|exe|scr|dmg|msi|appimage|pkg|7z|tar\.gz)$/i;

const prev = fs.existsSync(out) ? JSON.parse(fs.readFileSync(out, "utf8")) : { games: {} };
const games = {};
const game = (slug, title) => (games[slug] ??= { title: title ?? prev.games?.[slug]?.title ?? slug, listings: [] });

function titleOf(dir) {
  const file = path.join(root, dir, "index.html");
  if (!fs.existsSync(file)) return null;
  const m = fs.readFileSync(file, "utf8").match(/<title>([^<]+)<\/title>/i);
  return m ? m[1].split(/\s+[·—|]\s+/)[0].trim() : null;
}

// Site-served files.
const files = execFileSync("git", ["ls-files"], { cwd: root, encoding: "utf8" }).split("\n");
for (const f of files.filter((f) => DOWNLOAD.test(f) && !f.startsWith("v/") && !f.startsWith("tools/"))) {
  const dir = f.split("/")[0];
  if (!/^[a-z0-9][a-z0-9-]*$/i.test(dir) || dir === f) continue;
  const slug = dir.toLowerCase();
  game(slug, titleOf(dir)).listings.push({ platform: "site", kind: "site_asset", id: `/${f}`, label: path.basename(f) });
}

// CurseForge projects the release bot publishes to.
const watch = JSON.parse(fs.readFileSync(path.join(root, "tools/addon-watch/config.json"), "utf8"));
for (const a of Object.values(watch.addons)) {
  if (!a.curseforge?.project || !a.page) continue;
  game(a.page, titleOf(a.page)).listings.push({
    platform: "curseforge", kind: "curseforge_project", id: String(a.curseforge.project),
    label: `${a.name} on CurseForge`, from: "tools/addon-watch/config.json",
  });
}

// Hand-written entries survive.
for (const [slug, g] of Object.entries(prev.games ?? {})) {
  for (const l of g.listings ?? []) if (l.manual) game(slug, g.title).listings.push(l);
}

for (const g of Object.values(games)) g.listings.sort((a, b) => (a.platform + a.id).localeCompare(b.platform + b.id));
const sorted = Object.fromEntries(Object.entries(games).sort(([a], [b]) => a.localeCompare(b)));
const doc = {
  $comment: "Generated by tools/storefront-catalog.mjs; entries with \"manual\": true are kept as written. See docs/storefront-analytics.md.",
  firstPartyTrackingSince: prev.firstPartyTrackingSince ?? null,
  games: sorted,
};
fs.writeFileSync(out, JSON.stringify(doc, null, 1) + "\n");
const n = Object.values(sorted).reduce((s, g) => s + g.listings.length, 0);
console.log(`catalog: ${Object.keys(sorted).length} games, ${n} listings -> ${path.relative(root, out)}`);
